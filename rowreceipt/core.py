"""Create and compare authenticated, order-independent dataset receipts."""

import hashlib
import hmac
import math
import re
import sqlite3
import struct
import tempfile
from collections.abc import Iterable
from contextlib import closing
from dataclasses import dataclass
from operator import itemgetter
from pathlib import Path

from ._io import ReceiptError, canonical_json, read_bytes, read_json
from .contract import Contract, Field, valid_bucket_count
from .sources import MAX_ROW_BYTES

RECEIPT_FORMAT = "rowreceipt/1"
_MAX_RECEIPT_BYTES = 512 * 1024
_HEX_DIGEST = re.compile(r"[0-9a-f]{64}")
_INT_MIN, _INT_MAX = -(1 << 63), (1 << 63) - 1
_DOMAIN = b"rowreceipt/1\x00"


def read_key(path: str | Path) -> bytes:
    """Read a 32-byte binary key generated by keygen."""
    return _validate_key(read_bytes(path, 32))


def _validate_key(key):
    if type(key) is not bytes or len(key) != 32:
        raise ReceiptError("expected a 32-byte binary key")
    return key


def _derive(key, purpose, contract_digest):
    return hmac.digest(key, _DOMAIN + purpose + b"\x00" + contract_digest, "sha256")


def _encode(field: Field, value, row_number):
    if value is None and field.nullable:
        return b"N"
    if field.kind == "integer" and type(value) is int and _INT_MIN <= value <= _INT_MAX:
        return b"I" + struct.pack(">q", value)
    if field.kind == "real":
        if type(value) is int and _INT_MIN <= value <= _INT_MAX:
            converted = float(value)
            if int(converted) == value:
                value = converted
        if type(value) is float and math.isfinite(value):
            return b"R" + struct.pack(">d", 0.0 if value == 0 else value)
    if field.kind == "text" and type(value) is str and len(value) <= MAX_ROW_BYTES:
        try:
            encoded = value.encode("utf-8")
        except UnicodeEncodeError:
            raise ReceiptError(f"row {row_number}, field {field.name}: invalid UTF-8 text") from None
        if len(encoded) <= MAX_ROW_BYTES:
            return b"T" + struct.pack(">I", len(encoded)) + encoded
    if field.kind == "bytes" and type(value) is bytes and len(value) <= MAX_ROW_BYTES:
        return b"B" + struct.pack(">I", len(value)) + value
    raise ReceiptError(f"row {row_number}, field {field.name}: expected {field.kind} within limits")


def _is_digest(value):
    return isinstance(value, str) and _HEX_DIGEST.fullmatch(value) is not None


@dataclass(frozen=True, slots=True)
class Receipt:
    contract: str
    key_id: str
    buckets: tuple[tuple[int, str], ...]
    mac: str

    @classmethod
    def read(cls, path: str | Path) -> "Receipt":
        """Decode and structurally validate a serialized receipt."""
        return cls.from_dict(read_json(path, _MAX_RECEIPT_BYTES))

    @classmethod
    def from_dict(cls, document: dict) -> "Receipt":
        if not isinstance(document, dict) or document.keys() != {
            "format", "contract", "key_id", "buckets", "mac"
        } or document["format"] != RECEIPT_FORMAT:
            raise ReceiptError("expected a rowreceipt/1 document")
        if not all(_is_digest(document[name]) for name in ("contract", "key_id", "mac")):
            raise ReceiptError("invalid receipt digest")
        entries = document["buckets"]
        if not isinstance(entries, list) or not valid_bucket_count(len(entries)):
            raise ReceiptError("invalid receipt bucket count")
        buckets = []
        for item in entries:
            if (
                not isinstance(item, list) or len(item) != 2
                or type(item[0]) is not int or not 0 <= item[0] <= _INT_MAX
                or not _is_digest(item[1])
            ):
                raise ReceiptError("invalid receipt bucket")
            buckets.append((item[0], item[1]))
        if sum(count for count, _ in buckets) > _INT_MAX:
            raise ReceiptError("receipt row count exceeds the protocol limit")
        return cls(document["contract"], document["key_id"], tuple(buckets), document["mac"])

    def _payload(self):
        return {
            "format": RECEIPT_FORMAT,
            "contract": self.contract,
            "key_id": self.key_id,
            "buckets": [list(bucket) for bucket in self.buckets],
        }

    def to_bytes(self) -> bytes:
        """Encode as canonical UTF-8 JSON plus a newline."""
        return canonical_json({**self._payload(), "mac": self.mac}) + b"\n"

    @property
    def rows(self) -> int:
        return sum(count for count, _ in self.buckets)


def _receipt_mac(payload, key, contract_digest):
    return hmac.digest(
        _derive(key, b"receipt", contract_digest), canonical_json(payload), "sha256"
    ).hex()


def _fingerprints(rows, contract, key, contract_digest):
    indices = {field.name: index for index, field in enumerate(contract.fields)}
    key_indices = [indices[name] for name in contract.key]
    key_fields = itemgetter(*key_indices)
    key_mac = hmac.new(_derive(key, b"key", contract_digest), digestmod="sha256")
    row_mac = hmac.new(_derive(key, b"row", contract_digest), digestmod="sha256")
    composite_key = len(key_indices) > 1
    mask = contract.buckets - 1
    for number, row in enumerate(rows, start=1):
        if not isinstance(row, (tuple, list)) or len(row) != len(contract.fields):
            raise ReceiptError(f"row {number}: width differs from the contract")
        parts = []
        size = 0
        for field, value in zip(contract.fields, row):
            part = _encode(field, value, number)
            size += len(part)
            if size > MAX_ROW_BYTES:
                raise ReceiptError(f"row {number}: encoded row exceeds 8 MiB")
            parts.append(part)
        identity = key_fields(parts)
        key_hash = key_mac.copy()
        key_hash.update(b"".join(identity) if composite_key else identity)
        fingerprint = key_hash.digest()
        bucket = (fingerprint[0] << 8 | fingerprint[1]) & mask
        row_hash = row_mac.copy()
        row_hash.update(b"".join(parts))
        yield bucket, fingerprint, row_hash.digest()


def _reduce(db, contract, key, digest):
    secret = _derive(key, b"bucket", digest)
    buckets = []
    stream = db.execute("SELECT bucket, fingerprint, content FROM fingerprints ORDER BY bucket, fingerprint")
    item = next(stream, None)
    for bucket in range(contract.buckets):
        commitment = hmac.new(secret, struct.pack(">H", bucket), "sha256")
        count = 0
        while item is not None and item[0] == bucket:
            commitment.update(item[1])
            commitment.update(item[2])
            count += 1
            item = next(stream, None)
        buckets.append([count, commitment.hexdigest()])
    return buckets


def capture(
    rows: Iterable[tuple], contract: Contract, key: bytes, *, scratch_dir: str | Path | None = None
) -> Receipt:
    """Consume typed rows and produce a receipt with a private disk-backed index."""
    key = _validate_key(key)
    if not isinstance(contract, Contract) or Contract.from_dict(contract.as_dict()) != contract:
        raise ReceiptError("expected a validated Contract")
    digest = contract.digest()
    try:
        with tempfile.TemporaryDirectory(prefix="rowreceipt-", dir=scratch_dir) as scratch:
            with closing(sqlite3.connect(Path(scratch) / "fingerprints.sqlite")) as db:
                db.execute("PRAGMA journal_mode=OFF")
                db.execute("PRAGMA synchronous=OFF")
                db.execute("PRAGMA cache_size=-32768")
                db.execute("PRAGMA temp_store=FILE")
                db.execute(
                    "CREATE TABLE fingerprints (bucket INTEGER, fingerprint BLOB, content BLOB NOT NULL, "
                    "PRIMARY KEY (bucket, fingerprint)) WITHOUT ROWID"
                )
                try:
                    db.executemany(
                        "INSERT INTO fingerprints VALUES (?, ?, ?)",
                        _fingerprints(rows, contract, key, digest),
                    )
                except sqlite3.IntegrityError:
                    raise ReceiptError("duplicate logical key") from None
                buckets = _reduce(db, contract, key, digest)
    except sqlite3.Error as exc:
        code = getattr(exc, "sqlite_errorname", None)
        raise ReceiptError(f"scratch index failed ({code or 'SQLite error'})") from exc
    payload = {
        "format": RECEIPT_FORMAT, "contract": digest.hex(),
        "key_id": _derive(key, b"id", digest).hex(), "buckets": buckets,
    }
    return Receipt.from_dict({**payload, "mac": _receipt_mac(payload, key, digest)})


@dataclass(frozen=True, slots=True)
class BucketDifference:
    bucket: int
    left_rows: int
    right_rows: int


@dataclass(frozen=True, slots=True)
class Comparison:
    left_rows: int
    right_rows: int
    differences: tuple[BucketDifference, ...]

    @property
    def match(self) -> bool:
        return not self.differences


def _verify(receipt, key):
    payload = receipt._payload()
    Receipt.from_dict({**payload, "mac": receipt.mac})
    digest = bytes.fromhex(receipt.contract)
    expected_id = _derive(key, b"id", digest).hex()
    expected_mac = _receipt_mac(payload, key, digest)
    if not hmac.compare_digest(receipt.key_id, expected_id) or not hmac.compare_digest(receipt.mac, expected_mac):
        raise ReceiptError("receipt authentication failed")


def compare(left: Receipt, right: Receipt, key: bytes) -> Comparison:
    """Authenticate both receipts, check compatibility, and locate changed buckets."""
    key = _validate_key(key)
    _verify(left, key)
    _verify(right, key)
    if left.contract != right.contract or len(left.buckets) != len(right.buckets):
        raise ReceiptError("receipts use different contracts")
    differences = tuple(
        BucketDifference(index, a[0], b[0])
        for index, (a, b) in enumerate(zip(left.buckets, right.buckets))
        if a != b
    )
    return Comparison(left.rows, right.rows, differences)
